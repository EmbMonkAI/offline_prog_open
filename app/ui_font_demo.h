/* 取汉字（GBK 双字节码，高字节在 s[0]）点阵指针；未收录返回 NULL */
static const uint8_t *f24_chs(uint8_t hi, uint8_t lo)
{
    uint16_t code = (uint16_t)((hi << 8) | lo);
    for (uint16_t i = 0; i < F24_CHS_N; i++)
        if (f24_chs_code[i] == code)
            return f24_chs_bits[i];
    return 0;
}

/* 取 ASCII（0x20~0x7E）点阵指针；范围外返回 NULL */
static const uint8_t *f24_asc(uint8_t c)
{
    if (c < F24_ASC_FIRST || c >= F24_ASC_FIRST + F24_ASC_N)
        return 0;
    return f24_asc_bits[c - F24_ASC_FIRST];
}
